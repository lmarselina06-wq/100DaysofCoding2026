public class day28 {
    public static void main(String[] args) {
        // operator perbandingan == dan !=
        int angka1 = 10;
        int angka2 = 20;
        System.out.println("angka1 = "+ angka1);
        System.out.println("angka2 = "+ angka2);
        System.out.println("angka1 == angka2 : " + (angka1 == angka2));
        System.out.println("angka1 != angka2 : " + (angka1 != angka2));
    }
}
