public class day27 {
    public static void main(String[] args) {
        // Nilai awal
        int angka = 10;
        System.out.println("Nilai awal = " + angka);

        // Increment
        angka++;
        System.out.println("Setelah increment (angka++) = " + angka);

        // Increment lagi
        angka++;
        System.out.println("Setelah increment lagi (angka++) = " + angka);

        // Decrement
        angka--;
        System.out.println("Setelah decrement (angka--) = " + angka);

        // Decrement lagi
        angka--;
        System.out.println("Setelah decrement lagi (angka--) = " + angka);
    }
}
